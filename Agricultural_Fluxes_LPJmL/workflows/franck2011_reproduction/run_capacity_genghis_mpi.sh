#!/usr/bin/env bash
set -euo pipefail

# Final Genghis Khan branch: all eligible cells receive the single crop CFT
# selected by the capacity stage, with methane diagnostics enabled. Livestock,
# grazing and manure are disabled explicitly.  The methane-enabled spinup is
# repeated because a no-methane restart is not a valid state hand-off.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LPJML_ROOT=""
INPUT_ROOT=""
CAMPAIGN_DIR=""
LANDUSE_META=""
MPI_RANKS="${MPI_RANKS:-4}"
CHECKPOINT_INTERVAL="${CHECKPOINT_INTERVAL_SECONDS:-3600}"
PHASE="all"
DRY_RUN=0

usage() {
  cat <<'MSG'
Usage: run_capacity_genghis_mpi.sh [options]

Required:
  --lpjml-root DIR    Pinned LPJmL 6.0.6 MPI checkout.
  --input-root DIR    Verified public_standard input directory.
  --campaign-dir DIR  Persistent Linux-filesystem campaign directory.
  --landuse-meta FILE Crop-only CLM metadata generated by build_capacity_landuse.py.
  --mpi-ranks N       MPI processes (default: 4; 8 may exceed available memory).

Options:
  --phase spinup|managed|all  Run a recoverable phase (default all).
  --dry-run                    Validate and print commands without running LPJmL.
MSG
}

while (($#)); do
  case "$1" in
    --lpjml-root) LPJML_ROOT="$2"; shift 2 ;;
    --input-root) INPUT_ROOT="$2"; shift 2 ;;
    --campaign-dir) CAMPAIGN_DIR="$2"; shift 2 ;;
    --landuse-meta) LANDUSE_META="$2"; shift 2 ;;
    --mpi-ranks) MPI_RANKS="$2"; shift 2 ;;
    --phase) PHASE="$2"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ -z "$LPJML_ROOT" || -z "$INPUT_ROOT" || -z "$CAMPAIGN_DIR" || -z "$LANDUSE_META" ]]; then
  usage >&2
  exit 2
fi
if [[ "$PHASE" != "spinup" && "$PHASE" != "managed" && "$PHASE" != "all" ]]; then
  echo "--phase must be spinup, managed, or all" >&2
  exit 2
fi
if ! [[ "$MPI_RANKS" =~ ^[1-9][0-9]*$ ]]; then
  echo "--mpi-ranks must be a positive integer" >&2
  exit 2
fi
if [[ "$CAMPAIGN_DIR" == /mnt/* || "$LPJML_ROOT" == /mnt/* ]]; then
  echo "Put LPJmL and campaign outputs on the Linux filesystem, not /mnt/*." >&2
  exit 3
fi

EXPECTED_COMMIT="5af44a1ed023279a23c28d6dfe76945b97aaac57"
[[ "$(git -C "$LPJML_ROOT" rev-parse HEAD 2>/dev/null || true)" == "$EXPECTED_COMMIT" ]] || {
  echo "LPJmL source is not the pinned balance-fix commit" >&2
  exit 4
}
[[ -x "$LPJML_ROOT/bin/lpjml" && -x "$LPJML_ROOT/bin/lpjcheck" ]] || {
  echo "LPJmL binaries are missing under $LPJML_ROOT" >&2
  exit 4
}
command -v mpirun >/dev/null 2>&1 || { echo "mpirun is required" >&2; exit 4; }
((MPI_RANKS <= $(nproc))) || { echo "MPI ranks exceed available CPUs" >&2; exit 5; }
[[ -f "$LANDUSE_META" ]] || { echo "Missing crop-only map metadata: $LANDUSE_META" >&2; exit 6; }
LANDUSE_FILE="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["filename"])' "$LANDUSE_META")"
[[ -s "$(dirname "$LANDUSE_META")/$LANDUSE_FILE" ]] || {
  echo "Map data file referenced by metadata is missing: $(dirname "$LANDUSE_META")/$LANDUSE_FILE" >&2
  exit 6
}

mkdir -p "$CAMPAIGN_DIR/configs"
exec 9>"$CAMPAIGN_DIR/campaign.lock"
flock -n 9 || { echo "Campaign already locked: $CAMPAIGN_DIR" >&2; exit 9; }
exec >>"$CAMPAIGN_DIR/launcher.log" 2>&1
trap 'echo FAILED $(date -Is) >"$CAMPAIGN_DIR/campaign_status.txt"' ERR
unset OMP_NUM_THREADS OMP_THREAD_LIMIT
export OPENBLAS_NUM_THREADS=1

CONFIG_DIR="$CAMPAIGN_DIR/configs"
if [[ ! -f "$CONFIG_DIR/manifest.json" ]]; then
  python3 "$SCRIPT_DIR/prepare_configs.py" \
    --lpjml-root "$LPJML_ROOT" \
    --input-root "$INPUT_ROOT" \
    --output-dir "$CONFIG_DIR" \
    --mode global \
    --workflow global-a1 \
    --with-methane \
    --crop-only
fi

PATCHED_CONFIG="$CONFIG_DIR/genghis_khan_crop_only.json"
if [[ ! -f "$PATCHED_CONFIG" ]]; then
  python3 "$SCRIPT_DIR/patch_crop_only_config.py" \
    --source "$CONFIG_DIR/a1_2005_n.json" \
    --output "$PATCHED_CONFIG" \
    --landuse-meta "$LANDUSE_META" \
    --year 2005
fi

run_scenario() {
  local scenario="$1"
  local config="$2"
  local phase_status="$3"
  local scenario_dir="$CAMPAIGN_DIR/$scenario"
  mkdir -p "$scenario_dir/output" "$scenario_dir/restart"
  if [[ -f "$scenario_dir/run_status.txt" ]] && grep -q '^exit_code=0$' "$scenario_dir/run_status.txt"; then
    echo "Completed phase retained: $scenario"
    return
  fi
  local checkpoint_config="$scenario_dir/checkpoint_config.json"
  if [[ ! -f "$checkpoint_config" ]]; then
    python3 - "$config" "$checkpoint_config" "$scenario_dir/restart/checkpoint.lpj" <<'PY'
import json
from pathlib import Path
import sys
source, target, checkpoint = map(Path, sys.argv[1:])
config = json.loads(source.read_text())
config["checkpoint_filename"] = str(checkpoint)
target.write_text(json.dumps(config, indent=2) + "\n")
PY
  fi
  local command=(mpirun -np "$MPI_RANKS" "$LPJML_ROOT/bin/lpjml"
    -inpath "$INPUT_ROOT"
    -outpath "$scenario_dir"
    -restartpath "$scenario_dir/restart"
    "$checkpoint_config")
  printf 'COMMAND:'
  printf ' %q' "${command[@]}"
  printf '\n'
  [[ "$DRY_RUN" -eq 0 ]] || return
  "$LPJML_ROOT/bin/lpjcheck" \
    -inpath "$INPUT_ROOT" \
    -outpath "$scenario_dir" \
    -restartpath "$scenario_dir/restart" \
    "$checkpoint_config" >"$scenario_dir/lpjcheck.log" 2>&1
  printf 'phase=%s\nstarted_utc=%s\n' "$phase_status" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >"$scenario_dir/run_status.txt"
  python3 "$SCRIPT_DIR/checkpoint_runner.py" \
    --config "$checkpoint_config" \
    --phase-dir "$scenario_dir" \
    --interval-seconds "$CHECKPOINT_INTERVAL" \
    -- "${command[@]}" \
    >>"$scenario_dir/controller.log" 2>>"$scenario_dir/controller.stderr.log"
  printf 'completed_utc=%s\nexit_code=0\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >>"$scenario_dir/run_status.txt"
}

if [[ "$PHASE" == "spinup" || "$PHASE" == "all" ]]; then
  echo "GENGHIS_SPINUP_RUNNING $(date -Is)" >"$CAMPAIGN_DIR/campaign_status.txt"
  run_scenario spinup_natural "$CONFIG_DIR/spinup_natural.json" methane_spinup
  if [[ "$DRY_RUN" -eq 0 ]]; then
    [[ -s "$CAMPAIGN_DIR/spinup_natural/restart/restart_1700_nv_stdfire.lpj" ]] || {
      echo "Methane spinup restart is missing" >&2; exit 7;
    }
    echo "GENGHIS_SPINUP_COMPLETE $(date -Is)" >"$CAMPAIGN_DIR/campaign_status.txt"
  fi
fi

if [[ "$PHASE" == "managed" || "$PHASE" == "all" ]]; then
  SPINUP_RESTART="$CAMPAIGN_DIR/spinup_natural/restart/restart_1700_nv_stdfire.lpj"
  if [[ "$DRY_RUN" -eq 0 && ! -s "$SPINUP_RESTART" ]]; then
    echo "Managed phase cannot start: methane spinup restart is missing" >&2
    exit 7
  fi
  mkdir -p "$CAMPAIGN_DIR/genghis_khan_crop_only/restart"
  if [[ "$DRY_RUN" -eq 0 ]]; then
    cp -p "$SPINUP_RESTART" "$CAMPAIGN_DIR/genghis_khan_crop_only/restart/"
    sha256sum "$SPINUP_RESTART" >"$CAMPAIGN_DIR/spinup_restart.sha256"
    echo "GENGHIS_MANAGED_RUNNING $(date -Is)" >"$CAMPAIGN_DIR/campaign_status.txt"
  fi
  run_scenario genghis_khan_crop_only "$PATCHED_CONFIG" managed_crop_only
  if [[ "$DRY_RUN" -eq 0 ]]; then
    echo "GENGHIS_COMPLETE $(date -Is)" >"$CAMPAIGN_DIR/campaign_status.txt"
  fi
fi

printf 'campaign_dir=%s\nmap_metadata=%s\nmap_sha256=%s\n' \
  "$CAMPAIGN_DIR" "$LANDUSE_META" "$(sha256sum "$(dirname "$LANDUSE_META")/$LANDUSE_FILE" | awk '{print $1}')"
